import { C, circle, ellipse, rrect } from './levels';

function part(id: string, d: string, color: string, detail?: string) {
  return { id, d, color, detail };
}

function sheet(id: string, name: string, ...parts: ReturnType<typeof part>[]) {
  return { id, name, parts };
}

